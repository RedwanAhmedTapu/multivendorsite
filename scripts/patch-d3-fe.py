append = chr(10).join([
'',
'// == PHASE D3: HR Calendar + Letters ====================================',
'export interface CalendarEvent { date: string; type: string; title: string; employeeId?: string | null }',
'export interface HrLetterTemplate { id: string; type: string; name: string; subject: string; body: string; requiresApproval: boolean; active?: boolean }',
'export interface HrLetter {',
'  id: string; letterNumber: string; subject: string; content: string;',
'  type: string; status: "DRAFT" | "HR_REVIEW" | "APPROVED" | "ISSUED" | "REJECTED";',
'  employeeId: string; issuedAt?: string | null; createdAt: string;',
'  employee?: { id: string; code: string; fullName: string };',
'}',
'',
'const hrmD3Api = hrmApi.injectEndpoints({',
'  endpoints: (builder) => ({',
'    getCalendar: builder.query<{ success: boolean; data: { items: CalendarEvent[] } }, { from: string; to: string } | void>({',
'      query: (params) => ({ url: "/hrm/insights/calendar", params: params ?? undefined }),',
'      providesTags: ["HrEmployee"],',
'    }),',
'    getLetterTemplates: builder.query<{ success: boolean; data: HrLetterTemplate[] }, void>({',
'      query: () => "/hrm/letters/templates",',
'      providesTags: ["HrLetter"],',
'    }),',
'    createLetterTemplate: builder.mutation<{ success: boolean; data: HrLetterTemplate }, Partial<HrLetterTemplate>>({',
'      query: (body) => ({ url: "/hrm/letters/templates", method: "POST", body }),',
'      invalidatesTags: ["HrLetter"],',
'    }),',
'    updateLetterTemplate: builder.mutation<{ success: boolean; data: HrLetterTemplate }, { id: string; data: Partial<HrLetterTemplate> }>({',
'      query: ({ id, data }) => ({ url: `/hrm/letters/templates/${id}`, method: "PUT", body: data }),',
'      invalidatesTags: ["HrLetter"],',
'    }),',
'    generateLetter: builder.mutation<{ success: boolean; data: HrLetter }, { employeeId: string; templateId?: string; type: string; subject?: string; body?: string; effectiveDate?: string }>({',
'      query: (body) => ({ url: "/hrm/letters", method: "POST", body }),',
'      invalidatesTags: ["HrLetter"],',
'    }),',
'    getLetters: builder.query<{ success: boolean; data: HrLetter[] }, { status?: string; employeeId?: string } | void>({',
'      query: (params) => ({ url: "/hrm/letters", params: params ?? undefined }),',
'      providesTags: ["HrLetter"],',
'    }),',
'    approveLetter: builder.mutation<{ success: boolean; data: HrLetter }, string>({',
'      query: (id) => ({ url: `/hrm/letters/${id}/approve`, method: "PATCH" }),',
'      invalidatesTags: ["HrLetter"],',
'    }),',
'    issueLetter: builder.mutation<{ success: boolean; data: HrLetter }, string>({',
'      query: (id) => ({ url: `/hrm/letters/${id}/issue`, method: "PATCH" }),',
'      invalidatesTags: ["HrLetter"],',
'    }),',
'    getLetterPdfUrl: builder.query<{ success: boolean; data: HrLetter }, string>({',
'      query: (id) => `/hrm/letters/${id}`,',
'      providesTags: (r, e, id) => [{ type: "HrLetter", id }],',
'    }),',
'  }),',
'});',
'',
'export const {',
'  useGetCalendarQuery,',
'  useGetLetterTemplatesQuery,',
'  useCreateLetterTemplateMutation,',
'  useUpdateLetterTemplateMutation,',
'  useGenerateLetterMutation,',
'  useGetLettersQuery,',
'  useApproveLetterMutation,',
'  useIssueLetterMutation,',
'} = hrmD3Api;',
])
