function ActionButton({
  isLoading,
  loadingLabel,
  onClick,
  variant = "primary",
  children,
  icon,
  disabled,
}: {
  isLoading?: boolean;
  loadingLabel: string;
  onClick: () => void;
  variant?: "primary" | "outline";
  children: React.ReactNode;
  icon?: React.ReactNode;
  disabled?: boolean;
}) {
  const [isHovered, setIsHovered] = useState(false);
  const [isPressed, setIsPressed] = useState(false);
  const isPrimary = variant === "primary";
  const off = disabled || isLoading;

  return (
    <button
      type="button"
      onClick={onClick}
      onMouseEnter={() => setIsHovered(true)}
      onMouseLeave={() => {
        setIsHovered(false);
        setIsPressed(false);
      }}
      onMouseDown={() => setIsPressed(true)}
      onMouseUp={() => setIsPressed(false)}
      disabled={off}
      style={{
        padding: "11px 24px",
        borderRadius: 11,
        border: isPrimary ? "none" : "1.5px solid #C7D2FE",
        background: isPrimary
          ? isHovered
            ? "linear-gradient(135deg,#2563EB,#8B5CF6)"
            : "linear-gradient(135deg,#1D4ED8,#7C3AED)"
          : "#fff",
        color: isPrimary ? "#fff" : "#1D4ED8",
        fontSize: 13,
        fontWeight: 700,
        letterSpacing: "0.01em",
        cursor: off ? "not-allowed" : "pointer",
        fontFamily: "inherit",
        display: "inline-flex",
        alignItems: "center",
        justifyContent: "center",
        gap: 8,
        width: "100%",
        opacity: off ? 0.6 : 1,
        boxShadow: isPrimary
          ? isHovered
            ? "0 10px 24px rgba(124,58,237,0.35), 0 2px 6px rgba(29,78,216,0.25)"
            : "0 4px 14px rgba(124,58,237,0.25)"
          : "none",
        transform: isPressed ? "scale(0.97)" : isHovered ? "translateY(-1px)" : "translateY(0)",
        transition: "all 0.18s ease",
      }}
    >
      {isLoading ? (
        <>
          <Loader2 size={15} style={{ animation: "spin 1s linear infinite" }} />
          <span>{loadingLabel}</span>
        </>
      ) : (
        <>
          {icon}
          {children}
        </>
      )}
    </button>
  );
}

