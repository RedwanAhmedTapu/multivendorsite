/* ─── Helpers ───────────────────────────────────────────────────────────── */

interface CategoryAttr {
  name: string;
  type: string;
  isRequired: boolean;
  isVariant: boolean;
}

// CategoryTreeSelector can hand back either flat attributes or
// { attribute, isRequired } links — normalise both. Brand is skipped because
// the importer treats it separately (Product.brandId).
function normalizeAttributes(raw: any[]): CategoryAttr[] {
  return (raw ?? [])
    .map((a) => {
      const attr = a?.attribute ?? a;
      const type = String(attr?.type ?? "");
      const values = attr?.values;
      return {
        name: String(attr?.name ?? "").trim(),
        type,
        isRequired: Boolean(a?.isRequired ?? attr?.isRequired),
        isVariant: type === "SELECT" && (Array.isArray(values) ? values.length > 1 : true),
      };
    })
    .filter((a) => a.name && a.name.toLowerCase() !== "brand");
}

function formatRows(rows: number[]): string {
  const sorted = [...rows].sort((a, b) => a - b);
  if (!sorted.length) return "";
  const parts: string[] = [];
  let start = sorted[0];
  let prev = sorted[0];
  for (let i = 1; i <= sorted.length; i++) {
    const cur = sorted[i];
    if (cur === prev + 1) {
      prev = cur;
      continue;
    }
    parts.push(start === prev ? `${start}` : `${start}–${prev}`);
    start = cur;
    prev = cur;
  }
  return `${sorted.length > 1 ? "Rows" : "Row"} ${parts.join(", ")}`;
}

// Prisma errors arrive as a wall of text ("Invalid `prisma.product.create()`
// invocation: { data: … } Unknown argument …"). Keep the actionable last line
// as the headline and tuck the rest behind a toggle.
function splitError(message?: string): { short: string; full: string } {
  const full = (message ?? "").trim();
  if (!full) return { short: "Unknown error", full: "Unknown error" };
  if (/Invalid `prisma\./.test(full)) {
    const lines = full.split("\n").map((l) => l.trim()).filter(Boolean);
    return { short: lines[lines.length - 1] || full, full };
  }
  return { short: full, full };
}

