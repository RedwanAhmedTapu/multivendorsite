const BulkProductTemplate: React.FC = () => {
  // Category (single source of truth for download + upload)
  const [categoryId, setCategoryId] = useState<string | null>(null);
  const [isLeafCategory, setIsLeafCategory] = useState(false);
  const [selectedPath, setSelectedPath] = useState("");
  const [categoryAttributes, setCategoryAttributes] = useState<CategoryAttr[]>([]);

  // Collapsible panels
  const [showTemplate, setShowTemplate] = useState(false);
  const [showInstructions, setShowInstructions] = useState(false);
  const [showDetails, setShowDetails] = useState(false);

  // Download
  const [downloadError, setDownloadError] = useState<string | null>(null);
  const [downloadDone, setDownloadDone] = useState(false);
  const [triggerDownload, { isFetching: isDownloading }] = useLazyGetBulkImportTemplateQuery();

  // Upload
  const [file, setFile] = useState<File | null>(null);
  const [isDragging, setIsDragging] = useState(false);
  const [uploadError, setUploadError] = useState<string | null>(null);
  const [result, setResult] = useState<BulkImportSummary | null>(null);
  const fileInputRef = useRef<HTMLInputElement>(null);
  const [bulkUpload, { isLoading: isUploading }] = useBulkUploadProductsMutation();

  const categoryReady = Boolean(categoryId) && isLeafCategory;

  const requiredCount = categoryAttributes.filter((a) => a.isRequired).length;
  const variantAttrCount = categoryAttributes.filter((a) => a.isVariant).length;

  const groups = useMemo(() => {
    const list = (result?.results ?? [])
      .slice()
      .sort((a, b) => (a.rowNumbers[0] ?? 0) - (b.rowNumbers[0] ?? 0));
    return {
      failed: list.filter((g) => !g.success),
      saved: list.filter((g) => g.success),
      total: list.length,
    };
  }, [result]);

  const handleCategorySelect = (id: string, path: string, isLeaf: boolean, attributes: any[]) => {
    setCategoryId(id || null);
    setIsLeafCategory(isLeaf);
    setSelectedPath(path);
    setCategoryAttributes(normalizeAttributes(attributes));
    setDownloadDone(false);
    setDownloadError(null);
    setUploadError(null);
    setResult(null);
    // Once a usable category is picked, open the download panel for the vendor.
    if (id && isLeaf) setShowTemplate(true);
  };

  const handleDownload = async () => {
    if (!categoryId || !isLeafCategory) {
      setDownloadError("Please select a leaf category first.");
      return;
    }
    setDownloadError(null);
    try {
      const blob = await triggerDownload({ categoryId }).unwrap();
      const safeName =
        selectedPath.trim().replace(/[\\/:*?"<>|]+/g, "").replace(/\s+/g, "_") || categoryId;
      const url = window.URL.createObjectURL(blob);
      const a = document.createElement("a");
      a.href = url;
      a.download = `template_${safeName}.xlsx`;
      document.body.appendChild(a);
      a.click();
      window.URL.revokeObjectURL(url);
      document.body.removeChild(a);
      setDownloadDone(true);
      toast.success("Template downloaded successfully! 📥");
    } catch (err: any) {
      const msg = err?.data?.message ?? "Failed to download template. Please try again.";
      setDownloadError(msg);
      toast.error(msg);
    }
  };

  const clearFile = () => {
    setFile(null);
    if (fileInputRef.current) fileInputRef.current.value = "";
  };

  const pickFile = (f: File | null) => {
    setUploadError(null);
    if (!f) {
      setFile(null);
      return;
    }
    if (!/\.(xlsx|xls)$/i.test(f.name)) {
      toast.error("Please select a valid Excel file (.xlsx or .xls)");
      return;
    }
    if (f.size > MAX_FILE_BYTES) {
      toast.error("File too large. Maximum allowed size is 10MB.");
      return;
    }
    setFile(f);
    setResult(null);
    toast.info(`File selected: ${f.name}`);
  };

  const applyResult = (summary: BulkImportSummary) => {
    setResult(summary);
    setShowDetails(summary.failed > 0); // open the reasons straight away when something failed

    if (summary.failed === 0) {
      toast.success(`Import completed! ✅ ${summary.created} product(s) created.`, { duration: 5000 });
    } else if (summary.created === 0) {
      toast.error(`Import failed. ❌ All ${summary.failed} product(s) failed.`, { duration: 6000 });
    } else {
      toast.warning(`Import partial. ⚠️ ${summary.created} created, ${summary.failed} failed.`, { duration: 6000 });
    }
    (summary.warnings ?? []).forEach((w) => toast.warning(w, { duration: 4000 }));
  };

  const handleUpload = async () => {
    if (!categoryId || !isLeafCategory) {
      setUploadError("Select the category this file belongs to first.");
      return;
    }
    if (!file) {
      setUploadError("Choose the filled template file to upload.");
      return;
    }
    setUploadError(null);
    setResult(null);

    try {
      const summary = await bulkUpload({ categoryId, file }).unwrap();
      applyResult(summary);
      clearFile();
    } catch (err: any) {
      // When every product fails the server answers 422 but still sends the full
      // report in the body — RTK Query treats that as an error, so recover it here
      // instead of losing the per-product reasons.
      const payload = err?.data?.data as BulkImportSummary | undefined;
      if (payload && Array.isArray(payload.results)) {
        applyResult(payload);
        clearFile();
        return;
      }
      // Whole-file problems (duplicate SKU, wrong category, bad workbook, …)
      const msg = err?.data?.message ?? err?.error ?? "Upload failed. Please check the file and try again.";
      setUploadError(msg);
      toast.error(msg);
    }
  };

  const summaryTone = !result
    ? null
    : result.failed === 0
      ? ({ bg: "#F0FDF4", border: "#BBF7D0", bar: "#22C55E", icon: "#DCFCE7", title: "Import Successful 🎉" } as const)
      : result.created === 0
        ? ({ bg: "#FEF2F2", border: "#FECACA", bar: "#DC2626", icon: "#FEE2E2", title: "Import Failed ⚠️" } as const)
        : ({ bg: "#FFFBEB", border: "#FDE68A", bar: "#D97706", icon: "#FEF3C7", title: "Partial Import ⚠️" } as const);

  return (
    <div
      style={{
        fontFamily: "'Plus Jakarta Sans', system-ui, sans-serif",
        background: "#F0F4FA",
        minHeight: "100vh",
        padding: "24px 0",
      }}
    >
      <div style={{ maxWidth: "100%", padding: "0 16px" }}>
        <div style={{ display: "flex", flexDirection: "column", gap: 14 }}>
          {/* ════ 1. Category ════ */}
          <SectionCard
            id="bulkCategory"
            icon={<Layers size={15} color="#1D4ED8" />}
            title="Choose a Category"
            subtitle="This decides which attributes your template includes — it is used for both download and upload"
          >
            <CategoryTreeSelector onSelect={handleCategorySelect} />

            {categoryId && (
              <div style={{ marginTop: 12, display: "flex", flexDirection: "column", gap: 10 }}>
                <div
                  style={{
                    display: "flex",
                    alignItems: "center",
                    gap: 8,
                    borderRadius: 8,
                    padding: "8px 10px",
                    background: isLeafCategory ? "#F0FDF4" : "#FFFBEB",
                    border: `1px solid ${isLeafCategory ? "#BBF7D0" : "#FDE68A"}`,
                  }}
                >
                  {isLeafCategory ? (
                    <CheckCircle2 size={13} color="#16A34A" style={{ flexShrink: 0 }} />
                  ) : (
                    <AlertTriangle size={13} color="#D97706" style={{ flexShrink: 0 }} />
                  )}
                  <p style={{ fontSize: 11.5, fontWeight: 500, color: "#0D1B2E", overflow: "hidden", textOverflow: "ellipsis", whiteSpace: "nowrap" }}>
                    {selectedPath}
                  </p>
                </div>

                {!isLeafCategory && (
                  <p style={{ fontSize: 11, color: "#92400E", fontWeight: 500 }}>
                    Pick a more specific sub-category — this one still has children.
                  </p>
                )}

                {isLeafCategory && categoryAttributes.length > 0 && (
                  <div className="grid grid-cols-3 gap-2 sm:max-w-md">
                    <MiniStat label="Attributes" value={categoryAttributes.length} color="#0D1B2E" />
                    <MiniStat label="Required" value={requiredCount} color="#DC2626" />
                    <MiniStat label="Variant" value={variantAttrCount} color="#7C3AED" />
                  </div>
                )}
              </div>
            )}
          </SectionCard>

          {/* ════ 2. Download template (collapsible) ════ */}
          <SectionCard
            id="templateDownload"
            icon={<Download size={15} color="#1D4ED8" />}
            title="Download Template"
            subtitle="An .xlsx pre-built for the category above"
          >
            <div style={{ display: "flex", alignItems: "center", gap: 12, flexWrap: "wrap" }}>
              <ToggleButton
                open={showTemplate}
                onClick={() => setShowTemplate((v) => !v)}
                icon={<Settings size={14} />}
                openLabel="Hide Template Download"
                closedLabel="Show Template Download"
              />
              {!categoryReady && (
                <span style={{ fontSize: 11, color: "#9BAABB" }}>Select a leaf category above to enable the download.</span>
              )}
            </div>

            <AnimatePresence initial={false}>
              {showTemplate && (
                <motion.div
                  initial={{ opacity: 0, height: 0 }}
                  animate={{ opacity: 1, height: "auto" }}
                  exit={{ opacity: 0, height: 0 }}
                  transition={{ duration: 0.3 }}
                  style={{ overflow: "hidden" }}
                >
                  <div style={{ paddingTop: 16, display: "flex", flexDirection: "column", gap: 12 }}>
                    <div
                      style={{
                        display: "flex",
                        alignItems: "flex-start",
                        gap: 10,
                        background: "#FFFBEB",
                        border: "1px solid #FDE68A",
                        borderRadius: 10,
                        padding: "10px 14px",
                      }}
                    >
                      <AlertTriangle size={14} color="#D97706" style={{ marginTop: 1, flexShrink: 0 }} />
                      <p style={{ fontSize: 11.5, color: "#92400E", lineHeight: 1.6, fontWeight: 500 }}>{STOCK_NOTE}</p>
                    </div>

                    <div className="grid grid-cols-1 sm:grid-cols-2 gap-3">
                      <ActionButton
                        isLoading={isDownloading}
                        loadingLabel="Downloading..."
                        onClick={handleDownload}
                        disabled={!categoryReady}
                        icon={downloadDone ? <CheckCircle2 size={15} /> : <Download size={15} />}
                      >
                        {downloadDone ? "Downloaded — Re-download" : "Download .xlsx Template"}
                      </ActionButton>
                    </div>

                    {downloadError && (
                      <div
                        style={{
                          display: "flex",
                          alignItems: "flex-start",
                          gap: 8,
                          background: "#FEF2F2",
                          border: "1px solid #FECACA",
                          borderRadius: 9,
                          padding: "8px 12px",
                        }}
                      >
                        <AlertTriangle size={13} color="#DC2626" style={{ marginTop: 1, flexShrink: 0 }} />
                        <p style={{ fontSize: 11.5, color: "#B91C1C", fontWeight: 500 }}>{downloadError}</p>
                      </div>
                    )}
                  </div>
                </motion.div>
              )}
            </AnimatePresence>
          </SectionCard>

          {/* ════ 3. Upload + instructions + results ════ */}
          <SectionCard
            id="bulkImport"
            icon={<Upload size={15} color="#0891B2" />}
            title="Bulk Import Products"
            subtitle="Upload your filled template to create the products"
          >
            <div style={{ marginBottom: 16 }}>
              <ToggleButton
                open={showInstructions}
                onClick={() => setShowInstructions((v) => !v)}
                icon={<Info size={14} />}
                openLabel="Hide Instructions"
                closedLabel="Show Instructions"
              />
            </div>

            {/* ── Import report ── */}
            <AnimatePresence>
              {result && summaryTone && (
                <motion.div
                  initial={{ opacity: 0, y: -10 }}
                  animate={{ opacity: 1, y: 0 }}
                  exit={{ opacity: 0, y: -10 }}
                  style={{ marginBottom: 20 }}
                >
                  <div
                    style={{
                      background: summaryTone.bg,
                      border: `1px solid ${summaryTone.border}`,
                      borderLeft: `4px solid ${summaryTone.bar}`,
                      borderRadius: 10,
                      padding: "14px 16px",
                    }}
                  >
                    <div style={{ display: "flex", alignItems: "flex-start", gap: 12 }}>
                      <div
                        style={{
                          width: 28,
                          height: 28,
                          borderRadius: "50%",
                          background: summaryTone.icon,
                          display: "flex",
                          alignItems: "center",
                          justifyContent: "center",
                          flexShrink: 0,
                        }}
                      >
                        {result.failed === 0 ? (
                          <CheckCircle2 size={16} color="#16A34A" />
                        ) : result.created === 0 ? (
                          <XCircle size={16} color="#DC2626" />
                        ) : (
                          <AlertTriangle size={16} color="#D97706" />
                        )}
                      </div>

                      <div style={{ flex: 1, minWidth: 0 }}>
                        <p style={{ fontSize: 13, fontWeight: 700, color: "#0D1B2E" }}>{summaryTone.title}</p>
                        <p style={{ fontSize: 12, fontWeight: 500, color: "#3D5068", marginTop: 4 }}>
                          {result.created}/{result.totalGroups} product(s) created
                          {result.failed > 0 ? `, ${result.failed} failed` : ""}.
                          {result.failed > 0 && " See the reasons below and fix those rows in your file."}
                        </p>

                        <div className="grid grid-cols-2 sm:grid-cols-4 gap-3 mt-3">
                          <StatBox label="Total Rows" value={result.totalRows} />
                          <StatBox label="Products in File" value={result.totalGroups} />
                          <StatBox label="Created" value={result.created} tone="good" />
                          <StatBox label="Failed" value={result.failed} tone={result.failed > 0 ? "bad" : "neutral"} />
                        </div>

                        {groups.total > 0 && (
                          <div style={{ marginTop: 16 }}>
                            <button
                              type="button"
                              onClick={() => setShowDetails((v) => !v)}
                              style={{
                                display: "inline-flex",
                                alignItems: "center",
                                gap: 6,
                                fontSize: 12,
                                fontWeight: 600,
                                color: "#1D4ED8",
                                background: "#EEF3FB",
                                border: "1px solid #C7D2FE",
                                borderRadius: 8,
                                padding: "6px 12px",
                                cursor: "pointer",
                                fontFamily: "inherit",
                              }}
                            >
                              <ListChecks size={14} />
                              {showDetails ? "Hide Product Details" : `View Product Details (${groups.total})`}
                              {showDetails ? <ChevronUp size={14} /> : <ChevronDown size={14} />}
                            </button>

                            <AnimatePresence initial={false}>
                              {showDetails && (
                                <motion.div
                                  initial={{ opacity: 0, height: 0 }}
                                  animate={{ opacity: 1, height: "auto" }}
                                  exit={{ opacity: 0, height: 0 }}
                                  transition={{ duration: 0.3 }}
                                  style={{ overflow: "hidden", marginTop: 12 }}
                                >
                                  {groups.failed.length > 0 && (
                                    <div style={{ marginBottom: 12 }}>
                                      <p style={{ fontSize: 11, fontWeight: 700, color: "#7F1D1D", marginBottom: 6 }}>
                                        Not saved ({groups.failed.length})
                                      </p>
                                      {groups.failed.map((g) => (
                                        <GroupResultCard key={g.groupKey} group={g} />
                                      ))}
                                    </div>
                                  )}

                                  {groups.saved.length > 0 && (
                                    <div>
                                      <p style={{ fontSize: 11, fontWeight: 700, color: "#14532D", marginBottom: 6 }}>
                                        Saved ({groups.saved.length})
                                      </p>
                                      <div style={{ maxHeight: 256, overflowY: "auto" }}>
                                        {groups.saved.map((g) => (
                                          <GroupResultCard key={g.groupKey} group={g} />
                                        ))}
                                      </div>
                                    </div>
                                  )}
                                </motion.div>
                              )}
                            </AnimatePresence>
                          </div>
                        )}

                        {(result.warnings ?? []).length > 0 && (
                          <div style={{ marginTop: 12 }}>
                            <p style={{ fontSize: 11, fontWeight: 700, color: "#92400E", marginBottom: 6 }}>Warnings:</p>
                            <div style={{ display: "flex", flexDirection: "column", gap: 4 }}>
                              {(result.warnings ?? []).map((w, i) => (
                                <div
                                  key={i}
                                  style={{
                                    fontSize: 11,
                                    background: "#FFFBEB",
                                    border: "1px solid #FDE68A",
                                    borderRadius: 6,
                                    padding: "6px 10px",
                                    color: "#92400E",
                                  }}
                                >
                                  ⚠ {w}
                                </div>
                              ))}
                            </div>
                          </div>
                        )}
                      </div>
                    </div>
                  </div>
                </motion.div>
              )}
            </AnimatePresence>

            {/* ── Instructions (collapsible) ── */}
            <AnimatePresence initial={false}>
              {showInstructions && (
                <motion.div
                  initial={{ opacity: 0, height: 0 }}
                  animate={{ opacity: 1, height: "auto" }}
                  exit={{ opacity: 0, height: 0 }}
                  transition={{ duration: 0.3 }}
                  style={{ overflow: "hidden" }}
                >
                  <div
                    style={{
                      background: "#FFFBEB",
                      border: "1px solid #FDE68A",
                      borderRadius: 10,
                      padding: "14px 16px",
                      marginBottom: 16,
                    }}
                  >
                    <div style={{ display: "flex", alignItems: "center", gap: 8, marginBottom: 8 }}>
                      <AlertCircle size={16} color="#D97706" />
                      <span style={{ fontSize: 13, fontWeight: 700, color: "#78350F" }}>How the template works</span>
                    </div>
                    <ul style={{ fontSize: 12, color: "#92400E", lineHeight: 1.7, paddingLeft: 16, listStyle: "disc" }}>
                      <li>
                        <strong>One row per variant.</strong> Rows that share a <em>Variant Group No</em> become one product with several
                        variants; leave it blank for a standalone product.
                      </li>
                      <li>
                        Product-level fields (name, description, brand, tax, package &amp; warranty) are read from the{" "}
                        <strong>first row of each group</strong> — keep them identical across the group.
                      </li>
                      <li>
                        Columns marked <strong>*</strong> are required, and <strong>🔄</strong> marks variant attributes. Category attribute
                        values must match the dropdown options exactly.
                      </li>
                      <li>Every imported product is created as <strong>Pending approval</strong>, exactly like a manually added product.</li>
                      <li>
                        Each product is saved on its own — if one fails, the others still import and you get the reason for the failed ones.
                      </li>
                      <li>{STOCK_NOTE}</li>
                      <li>
                        <strong>Max 10MB</strong> per file (.xlsx or .xls).
                      </li>
                    </ul>
                  </div>

                  <div className="overflow-x-auto" style={{ marginBottom: 16 }}>
                    <div className="min-w-[720px] sm:min-w-0">
                      <Table className="border border-gray-200">
                        <TableHeader style={{ background: "#FAFBFD" }}>
                          <TableRow>
                            {["Section", "Column", "Required", "What to enter"].map((h) => (
                              <TableHead
                                key={h}
                                style={{ fontSize: 12, fontWeight: 700, color: "#0D1B2E", whiteSpace: "nowrap", padding: "10px 12px", borderBottom: "1px solid #E5EAF2" }}
                              >
                                {h}
                              </TableHead>
                            ))}
                          </TableRow>
                        </TableHeader>
                        <TableBody>
                          {TEMPLATE_COLUMNS.map((c) => (
                            <TableRow key={c.column} style={{ borderBottom: "1px solid #F0F4FA" }}>
                              <TableCell style={{ fontSize: 11, padding: "9px 12px", color: "#7A90AB", whiteSpace: "nowrap" }}>{c.section}</TableCell>
                              <TableCell style={{ fontSize: 12, padding: "9px 12px", fontWeight: 600, color: "#0D1B2E" }}>{c.column}</TableCell>
                              <TableCell style={{ padding: "9px 12px" }}>
                                <span
                                  style={{
                                    fontSize: 10,
                                    fontWeight: 700,
                                    padding: "2px 8px",
                                    borderRadius: 12,
                                    background: c.required === "Yes" ? "#FEF2F2" : c.required === "Ignored" ? "#F1F5F9" : "#F0FDF4",
                                    color: c.required === "Yes" ? "#DC2626" : c.required === "Ignored" ? "#64748B" : "#15803D",
                                  }}
                                >
                                  {c.required === "Yes" ? "Required" : c.required === "Ignored" ? "Not imported" : "Optional"}
                                </span>
                              </TableCell>
                              <TableCell style={{ fontSize: 11.5, padding: "9px 12px", color: "#3D5068" }}>{c.description}</TableCell>
                            </TableRow>
                          ))}

                          {categoryAttributes.map((a) => (
                            <TableRow key={`attr-${a.name}`} style={{ borderBottom: "1px solid #F0F4FA", background: "#FAFBFF" }}>
                              <TableCell style={{ fontSize: 11, padding: "9px 12px", color: "#7C3AED", whiteSpace: "nowrap" }}>Category attribute</TableCell>
                              <TableCell style={{ fontSize: 12, padding: "9px 12px", fontWeight: 600, color: "#0D1B2E" }}>
                                {a.name}
                                {a.isVariant ? " 🔄" : ""}
                              </TableCell>
                              <TableCell style={{ padding: "9px 12px" }}>
                                <span
                                  style={{
                                    fontSize: 10,
                                    fontWeight: 700,
                                    padding: "2px 8px",
                                    borderRadius: 12,
                                    background: a.isRequired ? "#FEF2F2" : "#F0FDF4",
                                    color: a.isRequired ? "#DC2626" : "#15803D",
                                  }}
                                >
                                  {a.isRequired ? "Required" : "Optional"}
                                </span>
                              </TableCell>
                              <TableCell style={{ fontSize: 11.5, padding: "9px 12px", color: "#3D5068" }}>
                                {a.type || "TEXT"} — {a.isVariant ? "varies per variant row; pick from the dropdown." : "same for the whole product."}
                              </TableCell>
                            </TableRow>
                          ))}
                        </TableBody>
                      </Table>
                    </div>
                  </div>

                  {!categoryReady && (
                    <p style={{ fontSize: 11, color: "#9BAABB", marginBottom: 16 }}>
                      Select a leaf category above to see that category&apos;s attribute columns in this table.
                    </p>
                  )}

                  <div
                    style={{
                      marginBottom: 16,
                      background: "#EEF3FB",
                      border: "1px solid #C7D2FE",
                      borderRadius: 10,
                      padding: "14px 16px",
                    }}
                  >
                    <p style={{ fontSize: 12, fontWeight: 700, color: "#0D1B2E", marginBottom: 8, display: "flex", alignItems: "center", gap: 6 }}>
                      <Sparkles size={14} color="#1D4ED8" />
                      Common reasons a product fails
                    </p>
                    <ul style={{ fontSize: 12, color: "#3D5068", lineHeight: 1.7, paddingLeft: 16, listStyle: "disc" }}>
                      <li>A required column (name, brand, SKU, package size) is blank.</li>
                      <li>An attribute value doesn&apos;t match one of the dropdown options exactly.</li>
                      <li>The SKU is already used by another product, or repeated in the file.</li>
                      <li>The category isn&apos;t a leaf category, or the file belongs to a different category.</li>
                    </ul>
                  </div>
                </motion.div>
              )}
            </AnimatePresence>

            {/* ── Upload zone ── */}
            <div style={{ marginTop: 4 }}>
              <FieldLabel hint="Supported formats: .xlsx / .xls (max 10MB)">Upload Filled Template</FieldLabel>
              <div style={{ display: "flex", flexDirection: "column", gap: 16 }}>
                <div
                  onDragOver={(e) => {
                    e.preventDefault();
                    setIsDragging(true);
                  }}
                  onDragLeave={() => setIsDragging(false)}
                  onDrop={(e) => {
                    e.preventDefault();
                    setIsDragging(false);
                    pickFile(e.dataTransfer.files?.[0] ?? null);
                  }}
                  onClick={() => fileInputRef.current?.click()}
                  style={{
                    border: `2px dashed ${isDragging || file ? "#1D4ED8" : "#C7D2FE"}`,
                    borderRadius: 12,
                    padding: "28px 24px",
                    textAlign: "center",
                    background: isDragging ? "#EEF3FB" : "#FAFBFD",
                    cursor: "pointer",
                    transition: "all 0.2s ease",
                  }}
                >
                  <input
                    ref={fileInputRef}
                    type="file"
                    accept=".xlsx,.xls"
                    style={{ display: "none" }}
                    onChange={(e) => pickFile(e.target.files?.[0] ?? null)}
                  />
                  <div style={{ display: "flex", flexDirection: "column", alignItems: "center", gap: 12 }}>
                    <div
                      style={{
                        width: 48,
                        height: 48,
                        borderRadius: 12,
                        background: file ? "#F0FDF4" : "#EEF3FB",
                        display: "flex",
                        alignItems: "center",
                        justifyContent: "center",
                      }}
                    >
                      {file ? <FileSpreadsheet size={22} color="#16A34A" /> : <UploadCloud size={22} color="#1D4ED8" />}
                    </div>
                    <div>
                      <p style={{ fontSize: 13, fontWeight: 600, color: "#0D1B2E", display: "flex", alignItems: "center", justifyContent: "center", gap: 8, flexWrap: "wrap" }}>
                        {file ? file.name : "Click to upload or drag and drop"}
                        {file && (
                          <button
                            type="button"
                            onClick={(e) => {
                              e.stopPropagation();
                              clearFile();
                            }}
                            aria-label="Remove file"
                            style={{ background: "none", border: "none", cursor: "pointer", color: "#9BAABB", display: "inline-flex" }}
                          >
                            <X size={14} />
                          </button>
                        )}
                      </p>
                      <p style={{ fontSize: 11, color: "#7A90AB", marginTop: 4 }}>
                        {file ? `${(file.size / 1024).toFixed(2)} KB` : "Excel (.xlsx / .xls) — max 10MB"}
                      </p>
                    </div>
                  </div>
                </div>

                {uploadError && (
                  <div
                    style={{
                      display: "flex",
                      alignItems: "flex-start",
                      gap: 8,
                      background: "#FEF2F2",
                      border: "1px solid #FECACA",
                      borderRadius: 9,
                      padding: "10px 12px",
                    }}
                  >
                    <AlertTriangle size={14} color="#DC2626" style={{ marginTop: 1, flexShrink: 0 }} />
                    <div>
                      <p style={{ fontSize: 12, color: "#B91C1C", fontWeight: 600 }}>Nothing was imported</p>
                      <p style={{ fontSize: 11.5, color: "#B91C1C", marginTop: 2, wordBreak: "break-word" }}>{uploadError}</p>
                    </div>
                  </div>
                )}

                {!categoryReady && (
                  <p style={{ fontSize: 11, color: "#9BAABB" }}>Select a leaf category above before importing.</p>
                )}

                <ActionButton
                  onClick={handleUpload}
                  isLoading={isUploading}
                  loadingLabel="Importing..."
                  disabled={!file || !categoryReady}
                  icon={<FileCheck size={15} />}
                >
                  Process Import
                </ActionButton>
              </div>
            </div>
          </SectionCard>
        </div>
      </div>

      <style>{`
        @keyframes spin { to { transform: rotate(360deg); } }
      `}</style>
    </div>
  );
};

export default BulkProductTemplate;